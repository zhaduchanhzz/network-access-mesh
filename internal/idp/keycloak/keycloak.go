// Package keycloak is the IdP driver for the Keycloak the platform hosts (§8.2, driver=keycloak): one realm per
// tenant plus the realm platform, administered through the Admin REST API.
//
// Least privilege — three identities, every credential read from the SecretStore by reference (DEK platform_ops:
// only the worker can read them):
//
//   - provisioning identity (Config.Provisioner): a confidential client of the master realm whose service account
//     holds only the realm role create-realm (no admin role, no master-realm client role). Keycloak gives the creator
//     of a realm every role of that realm's management client except impersonation; the driver uses this identity
//     only for realm-level work: create, reconcile, disable, delete realms and their clients. Bootstrap creates it
//     once with the break-glass admin of the master realm, which the driver itself never uses;
//   - per-realm service account mg-idp-driver (realm-management manage-users, view-users, query-users only, scope
//     limited to those roles): every day-to-day user operation (InviteUser, DisableUser). Its secret is generated by
//     the driver, stored first, then set at Keycloak;
//   - the Portal client mg-portal (Authorization Code + PKCE S256, no implicit/password grant, one exact redirect URI
//     https://<app|admin host>/api/v1/auth/callback/<idpId> — §8.3): its secret is stored for the api (tenant DEK, or
//     DEK platform for the platform IdP).
//
// Realms are created from realm.json.tmpl, a byte copy of infrastructure/idp/realms/tenant-a.json.tmpl (single
// source: TestTemplateIsInfrastructureTemplate fails on any difference, TestTemplateMatchesInfrastructure checks that
// the per-realm values the driver sets reproduce the three rendered infrastructure realms exactly). EnsureIssuer on an
// existing realm compares it with the same template and repairs drift: realm settings, the MFA browser flow
// requirements, required actions, the clients of the template, the service-account roles and scope mappings.
//
// Every call goes through the idp.PlatformRoute (https://auth.<domain>, TLS verified for that name, only /realms/ and
// /admin/realms paths); impersonation is never called and is disabled at the server (feature off — P2-T05).
package keycloak

import (
	"encoding/json"
	"errors"
	"log/slog"
	"regexp"
	"strings"
	"time"

	"github.com/google/uuid"

	"github.com/zhaduchanhzz/network-access-mesh/internal/idp"
	"github.com/zhaduchanhzz/network-access-mesh/internal/secrets"
)

// Client ids of the template and the provisioning identity.
const (
	PortalClientID             = "mg-portal"
	DriverClientID             = "mg-idp-driver"
	DefaultProvisionerClientID = "mg-provisioner"
	masterRealm                = "master"
	realmManagement            = "realm-management"
)

// Default SecretStore names (the <name> of mgsec://platform/<name>#<version>) of the platform_ops credentials.
const (
	ProvisionerRefName    = "idp.keycloak.provisioner"
	BootstrapAdminRefName = "idp.keycloak.bootstrap-admin"
)

// Credentials names a confidential client and the SecretStore reference of its secret.
type Credentials struct {
	ClientID string
	Secret   secrets.Ref
}

// Config configures the driver.
type Config struct {
	// Route is the narrow path to the platform-hosted IdP (required). Issuers are Route.BaseURL()+"/realms/<realm>".
	Route *idp.PlatformRoute
	// Secrets resolves every credential and stores the secrets the driver generates (required).
	Secrets secrets.SecretStore
	// Provisioner is the provisioning identity of the master realm (Bootstrap creates it).
	Provisioner Credentials
	// AppHost and AdminHost are the Portal origins (app./admin. + MG_BASE_DOMAIN): the redirect URI of a tenant IdP is
	// on AppHost, the platform IdP's on AdminHost (§8.3 step 3).
	AppHost, AdminHost string
	Logger             *slog.Logger
	Now                func() time.Time
}

// Driver is the keycloak IdP driver.
type Driver struct {
	*admin
	prov      Credentials
	appHost   string
	adminHost string
}

var _ idp.IdPDriver = (*Driver)(nil)

var hostRE = regexp.MustCompile(`^([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$`)

// New returns the driver.
func New(cfg Config) (*Driver, error) {
	var errs []error
	if cfg.Route == nil {
		errs = append(errs, errors.New("a platform route is required"))
	}
	if cfg.Secrets == nil {
		errs = append(errs, errors.New("a SecretStore is required"))
	}
	if cfg.Provisioner.ClientID == "" || cfg.Provisioner.Secret.Validate() != nil || !cfg.Provisioner.Secret.IsPlatform() {
		errs = append(errs, errors.New("the provisioner needs a client id and a platform secret reference"))
	}
	app, adm := strings.ToLower(cfg.AppHost), strings.ToLower(cfg.AdminHost)
	if !hostRE.MatchString(app) || !hostRE.MatchString(adm) || app == adm {
		errs = append(errs, errors.New("AppHost and AdminHost must be two DNS host names"))
	}
	if err := errors.Join(errs...); err != nil {
		return nil, errors.Join(errors.New("keycloak: invalid configuration"), err)
	}
	return &Driver{admin: newAdmin(cfg.Route, cfg.Secrets, cfg.Logger, cfg.Now), prov: cfg.Provisioner,
		appHost: app, adminHost: adm}, nil
}

// Name implements idp.IdPDriver.
func (d *Driver) Name() string { return idp.DriverKeycloak }

// Issuer returns the issuer of realm: https://<platform IdP host>/realms/<realm>.
func (d *Driver) Issuer(realm string) string { return d.base + "/realms/" + realm }

// redirectURI is the Portal callback of an IdP (§8.3 step 3): admin origin for the platform, app origin for tenants.
func (d *Driver) redirectURI(reg idp.Registration) string {
	host := d.appHost
	if reg.Scope == idp.ScopePlatform {
		host = d.adminHost
	}
	return "https://" + host + "/api/v1/auth/callback/" + reg.IdPID.String()
}

func (d *Driver) provisioner() tokenSource {
	return tokenSource{realm: masterRealm, clientID: d.prov.ClientID, secret: d.prov.Secret}
}

func realmToken(realm string, secret secrets.Ref) tokenSource {
	return tokenSource{realm: realm, clientID: DriverClientID, secret: secret}
}

// realmRE: realm names the driver creates or manages — DNS-label shaped (the realm is part of the issuer URL).
var realmRE = regexp.MustCompile(`^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$`)

func validRealm(r string) bool { return realmRE.MatchString(r) && r != masterRealm }

// DriverRef is identity_providers.driver_ref of a keycloak IdP: the realm and the reference of the secret of its
// mg-idp-driver service account.
type DriverRef struct {
	Realm        string `json:"realm"`
	DriverSecret string `json:"driver_secret_ref"`
}

// Encode returns the stored form (compact JSON).
func (r DriverRef) Encode() string {
	b, _ := json.Marshal(r) //nolint:errchkjson // two strings
	return string(b)
}

// ParseDriverRef parses and validates a stored driver_ref.
func ParseDriverRef(s string) (DriverRef, secrets.Ref, error) {
	var r DriverRef
	dec := json.NewDecoder(strings.NewReader(s))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&r); err != nil || !validRealm(r.Realm) {
		return DriverRef{}, secrets.Ref{}, idp.NewError(idp.CodeInvalidArgument, "keycloak", "driver_ref", nil)
	}
	ref, err := secrets.ParseRef(r.DriverSecret)
	if err != nil || !ref.IsPlatform() {
		return DriverRef{}, secrets.Ref{}, idp.NewError(idp.CodeInvalidArgument, "keycloak", "driver_ref_secret", nil)
	}
	return r, ref, nil
}

// driverSecretRef is the base reference of the mg-idp-driver secret of an IdP (platform_ops).
func driverSecretRef(idpID uuid.UUID) secrets.Ref {
	return secrets.PlatformRef("idp."+idpID.String()+".driver", 1)
}
