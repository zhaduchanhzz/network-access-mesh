// Sinh src/auth/rbac.gen.ts từ database/seeds/rbac.sql (seed RBAC sinh từ ma trận §8.5/§8.6 — P2-T07): bảng role →
// permission mà SPA dùng để ẩn/hiện mục điều hướng. Chỉ là UX — quyền do server quyết định ở mỗi request (§8.8, §12.1).
// `npm run gen:rbac`; test src/auth/rbac.test.ts fail khi file đã commit lệch seed.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
export const SEED = join(HERE, "../../../database/seeds/rbac.sql");
export const OUT = join(HERE, "../src/auth/rbac.gen.ts");

const GRANT_RE = /^\s*\('(platform|tenant|support)', '([a-z_]+)', '([a-z_]+\.[a-z_]+:[a-z_]+)', '(any|own)', (?:NULL|'[a-z_]+')\),?$/;

/** @param {string} sql nội dung rbac.sql @returns {string} nội dung rbac.gen.ts */
export function renderRbac(sql) {
  /** @type {Map<string, {scope: string, perms: Map<string, string>}>} */
  const roles = new Map();
  for (const line of sql.split(/\r?\n/)) {
    const m = GRANT_RE.exec(line);
    if (!m) continue;
    const [, scope, role, perm, grantScope] = m;
    if (!roles.has(role)) roles.set(role, { scope, perms: new Map() });
    roles.get(role).perms.set(perm, grantScope);
  }
  if (roles.size === 0) throw new Error("rbac.sql: không đọc được grant nào");
  const names = [...roles.keys()].sort();
  const out = [
    "// Code generated by scripts/gen-rbac.mjs from database/seeds/rbac.sql. DO NOT EDIT.",
    "// Role → permission (scope `any` | `own`) của ma trận §8.5/§8.6 — chỉ dùng cho điều hướng theo role (UX); server",
    "// kiểm quyền ở mỗi request (§8.8).",
    "",
    'export type GrantScope = "any" | "own";',
    'export type RoleScope = "platform" | "tenant" | "support";',
    "",
    "export const ROLE_SCOPE: Readonly<Record<string, RoleScope>> = {",
    ...names.map((r) => `  ${r}: "${roles.get(r).scope}",`),
    "};",
    "",
    "export const ROLE_PERMISSIONS: Readonly<Record<string, Readonly<Record<string, GrantScope>>>> = {",
  ];
  let grants = 0;
  for (const r of names) {
    out.push(`  ${r}: {`);
    for (const p of [...roles.get(r).perms.keys()].sort()) {
      out.push(`    "${p}": "${roles.get(r).perms.get(p)}",`);
      grants++;
    }
    out.push("  },");
  }
  out.push("};", "", `export const GRANT_COUNT = ${grants};`, "");
  return out.join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = renderRbac(readFileSync(SEED, "utf8"));
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}`);
}
