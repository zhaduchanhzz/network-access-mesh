// filterAllows reports whether a packet filter lets src reach dst:port (any rule, any protocol of the rule).
func filterAllows(mr *tailcfg.MapResponse, src netip.Addr, dst netip.Addr, port uint16) bool {
	rules := slices.Clone(mr.PacketFilter)
	for _, rs := range mr.PacketFilters {
		rules = append(rules, rs...)
	}
	contains := func(spec string, a netip.Addr) bool {
		if spec == "*" {
			return true
		}
		if p, err := netip.ParsePrefix(spec); err == nil {
			return p.Contains(a)
		}
		if x, err := netip.ParseAddr(spec); err == nil {
			return x == a
		}
		if lo, hi, ok := strings.Cut(spec, "-"); ok { // an IP range ("a-b"), as Headscale writes merged sets
			l, err1 := netip.ParseAddr(lo)
			h, err2 := netip.ParseAddr(hi)
			return err1 == nil && err2 == nil && l.BitLen() == a.BitLen() && l.Compare(a) <= 0 && a.Compare(h) <= 0
		}
		return false
	}
	for _, r := range rules {
		if !slices.ContainsFunc(r.SrcIPs, func(s string) bool { return contains(s, src) }) {
			continue
		}
		for _, dp := range r.DstPorts {
			if contains(dp.IP, dst) && port >= dp.Ports.First && port <= dp.Ports.Last {
				return true
			}
		}
	}
	return false
}

// filterRules describes the rules of a packet filter (diagnostics of a failure): "src→dst:ports" per entry.
func filterRules(mr *tailcfg.MapResponse) string {
	rules := slices.Clone(mr.PacketFilter)
	for _, rs := range mr.PacketFilters {
		rules = append(rules, rs...)
	}
	var out []string
	for _, r := range rules {
		for _, dp := range r.DstPorts {
			out = append(out, fmt.Sprintf("%v→%s:%d-%d", r.SrcIPs, dp.IP, dp.Ports.First, dp.Ports.Last))
		}
	}
	return strings.Join(out, "; ")
}

func ipv4Of(t *testing.T, n headscale.Node) netip.Addr {
	t.Helper()
	for _, a := range n.IPAddresses {
		if a.Is4() {
			return a
		}
	}
	t.Fatalf("node %d has no IPv4 address", n.ID)
	return netip.Addr{}
}

// testsOutcome is what CheckPolicy says about a policy + tests: "accepted", "refused: tests" (the block failed) or
// "refused: <kind>" (refused for another reason).
func testsOutcome(err error) string {
	if err == nil {
		return "accepted"
	}
	if he, ok := headscale.AsError(err); ok && strings.Contains(he.Upstream, "test(s) failed") {
		return "refused: tests"
	}
	return "refused: " + describe(err)
}

func TestP12_V24_TestsViaAndSelf(t *testing.T) {
	e := setup(t)
	inst := e.inst(t)
	c := ctx(t)
	before, err := inst.GetPolicy(c)
	if err != nil {
		t.Fatalf("GetPolicy: %s", describe(err))
	}
	declare := `{"tagOwners":{"` + v24RouterTag + `":[],"` + v24WebTag + `":[]},"grants":[],"ssh":[]}`
	if _, err := inst.SetPolicy(c, declare); err != nil {
		t.Fatalf("declare the tags: %s", describe(err))
	}

	// Inventory: user A (two devices), user B (one), a router tagged tag:ct-v24-router with the subnet approved. Users
	// are named mg-<membership> as the platform names them (§7.2).
	memA, memB := uuid.New(), uuid.New()
	userA := e.ensureUser(t, inst, "mg-"+memA.String())
	userB := e.ensureUser(t, inst, "mg-"+memB.String())
	a1, a2, b1, r1 := newFakeNode("ct-v24-a1"), newFakeNode("ct-v24-a2"), newFakeNode("ct-v24-b1"), newFakeNode("ct-v24-r1")
	r1.Routes = []netip.Prefix{netip.MustParsePrefix(v24Subnet)}
	e.registerWithKey(t, a1, e.userKey(t, inst, userA.ID), time.Time{})
	e.registerWithKey(t, a2, e.userKey(t, inst, userA.ID), time.Time{})
	e.registerWithKey(t, b1, e.userKey(t, inst, userB.ID), time.Time{})
	e.registerWithKey(t, r1, e.tagKey(t, inst, v24RouterTag), time.Time{})
	nA1, nA2, nB1, nR1 := e.nodeOf(t, inst, a1), e.nodeOf(t, inst, a2), e.nodeOf(t, inst, b1), e.nodeOf(t, inst, r1)
	t.Cleanup(func() {
		cc := ctx(t)
		for _, n := range []headscale.Node{nA1, nA2, nB1, nR1} {
			_ = inst.DeleteNode(cc, n.ID)
		}
		if _, err := inst.SetPolicy(cc, before.Data); err != nil {
			t.Errorf("restore the policy: %s", describe(err))
		}
		if now, err := inst.GetPolicy(cc); err != nil || now.Data != before.Data {
			t.Errorf("the policy was not restored byte for byte")
		}
	})
	// the router announces its subnet in a map session (Hostinfo.RoutableIPs — V-28), then the route is approved
	_, stopR := e.mapSession(t, r1)
	if _, err := inst.SetApprovedRoutes(c, nR1.ID, []netip.Prefix{netip.MustParsePrefix(v24Subnet)}); err != nil {
		stopR()
		t.Fatalf("SetApprovedRoutes: %s", describe(err))
	}
	time.Sleep(2 * time.Second)
	stopR()
	if rn := e.nodeOf(t, inst, r1); len(rn.SubnetRoutes) != 1 {
		t.Fatalf("router routes: %s", routes(rn))
	}
	ipA1, ipA2, ipB1 := ipv4Of(t, nA1), ipv4Of(t, nA2), ipv4Of(t, nB1)
	tokA := "mg-" + memA.String() + "@"

	pol := func(grant string, tests ...string) string {
		s := `{"tagOwners":{"` + v24RouterTag + `":[],"` + v24WebTag + `":[]},"grants":[` + grant + `],"ssh":[]`
		if len(tests) > 0 {
			s += `,"tests":[` + strings.Join(tests, ",") + `]`
		}
		return s + "}"
	}
	check := func(p string) string { return testsOutcome(inst.CheckPolicy(c, p)) }

	// --- via -------------------------------------------------------------------------------------------------------
	viaGrant := `{"src":["` + tokA + `"],"dst":["` + v24Subnet + `"],"ip":["tcp:80"],"via":["` + v24RouterTag + `"]}`
	plainGrant := `{"src":["` + tokA + `"],"dst":["` + v24Subnet + `"],"ip":["tcp:80"]}`
	acceptSubnet := `{"src":"` + tokA + `","proto":"tcp","accept":["` + v24InSubnet + `:80"]}`
	denySubnet := `{"src":"` + tokA + `","proto":"tcp","deny":["` + v24InSubnet + `:80"]}`
	via := map[string]string{
		"control accept (no via)": check(pol(plainGrant, acceptSubnet)),
		"control deny (no via)":   check(pol(plainGrant, denySubnet)),
		"accept, via only":        check(pol(viaGrant, acceptSubnet)),
		"deny, via only":          check(pol(viaGrant, denySubnet)),
	}
	// the via grant is effective: the router enforces A → subnet:80
	if _, err := inst.SetPolicy(c, pol(viaGrant)); err != nil {
		t.Fatalf("SetPolicy(via): %s", describe(err))
	}
	mr, stop := e.mapSession(t, r1)
	viaEffective := filterAllows(mr, ipA1, netip.MustParseAddr(v24InSubnet), 80)
	stop()
	if via["control accept (no via)"] != "accepted" || via["control deny (no via)"] != "refused: tests" || !viaEffective {
		t.Fatalf("via controls: %v, effective on the router %v (filter %s, %s; A %s)", via, viaEffective, filterRules(mr), routes(e.nodeOf(t, inst, r1)), ipA1)
	}
	viaVerdict := "VERIFIED (tests khẳng định được)"
	if via["accept, via only"] != "accepted" {
		viaVerdict = "UNSUPPORTED (tests KHÔNG khẳng định được quyền chỉ đến từ via)"
	}
	e.record(t, "V-24", "tests với quyền chỉ đến từ via (grant "+tokA+" → "+v24Subnet+" tcp:80 via "+v24RouterTag+", route đã duyệt)",
		fmt.Sprintf("đối chứng không via: accept ⇒ %s, deny ⇒ %s; chỉ via: accept ⇒ %s, deny ⇒ %s; router nhận rule A→%s:80 trong packet filter = %v ⇒ %s",
			via["control accept (no via)"], via["control deny (no via)"], via["accept, via only"], via["deny, via only"], v24InSubnet,
			viaEffective, viaVerdict),
		"testgen: grant có via không sinh ca (via_not_assertable) + Info tests:via_not_asserted")

	// --- autogroup:self --------------------------------------------------------------------------------------------
	selfGrant := `{"src":["autogroup:member"],"dst":["autogroup:self"],"ip":["tcp:22"]}`
	memberGrant := `{"src":["autogroup:member"],"dst":["autogroup:member"],"ip":["tcp:22"]}`
	acceptOwn := `{"src":"` + tokA + `","proto":"tcp","accept":["` + ipA2.String() + `:22"]}`
	denyOwn := `{"src":"` + tokA + `","proto":"tcp","deny":["` + ipA2.String() + `:22"]}`
	denyOther := `{"src":"` + tokA + `","proto":"tcp","deny":["` + ipB1.String() + `:22"]}`
	acceptSelfAlias := `{"src":"` + tokA + `","proto":"tcp","accept":["autogroup:self:22"]}`
	self := map[string]string{
		"control accept (member)":         check(pol(memberGrant, acceptOwn)),
		"accept own device, self only":    check(pol(selfGrant, acceptOwn)),
		"deny own device, self only":      check(pol(selfGrant, denyOwn)),
		"deny other user, self only":      check(pol(selfGrant, denyOther)),
		"accept autogroup:self:22 as dst": check(pol(selfGrant, acceptSelfAlias)),
	}
	if _, err := inst.SetPolicy(c, pol(selfGrant)); err != nil {
		t.Fatalf("SetPolicy(self): %s", describe(err))
	}
	mr = e.firstMap(t, a2)
	selfEffective := filterAllows(mr, ipA1, ipA2, 22)
	otherBlocked := !filterAllows(e.firstMap(t, b1), ipA1, ipB1, 22)
	if self["control accept (member)"] != "accepted" || !selfEffective || !otherBlocked {
		t.Fatalf("self controls: %v, effective on A's device %v (filter %s), B's device closed to A %v", self, selfEffective,
			filterRules(mr), otherBlocked)
	}
	selfVerdict := "VERIFIED (tests khẳng định được)"
	if self["accept own device, self only"] != "accepted" {
		selfVerdict = "UNSUPPORTED (tests KHÔNG khẳng định được quyền chỉ đến từ autogroup:self)"
	}
	e.record(t, "V-24", "tests với quyền chỉ đến từ autogroup:self (grant autogroup:member → autogroup:self tcp:22)",
		fmt.Sprintf("đối chứng member→member: accept ⇒ %s; chỉ self: accept thiết bị của chính A ⇒ %s, deny thiết bị của chính A ⇒ %s, deny thiết bị của B ⇒ %s, accept \"autogroup:self:22\" ⇒ %s; thiết bị a2 nhận rule a1→a2:22 = %v, b1 không mở cho a1 = %v ⇒ %s",
			self["control accept (member)"], self["accept own device, self only"], self["deny own device, self only"],
			self["deny other user, self only"], self["accept autogroup:self:22 as dst"], selfEffective, otherBlocked, selfVerdict),
		"testgen: đích chỉ autogroup:self không sinh ca (self_not_assertable) + Info tests:self_not_asserted")

	// --- generated tests over the real inventory --------------------------------------------------------------------
	eng, ops, router, web, lab, host := uuid.New(), uuid.New(), uuid.New(), uuid.New(), uuid.New(), uuid.New()
	in := &policies.RenderInputs{
		Groups: map[uuid.UUID]policies.RenderGroup{eng: {Name: "ct-v24-eng", Members: []uuid.UUID{memA}},
			ops: {Name: "ct-v24-ops", Members: []uuid.UUID{memB}}},
		Memberships: map[uuid.UUID]string{memA: "active", memB: "active"},
		Tags: map[uuid.UUID]policies.RenderTag{router: {Name: v24RouterTag, PlatformManaged: true},
			web: {Name: v24WebTag}},
		Catalog: []string{v24RouterTag, v24WebTag},
		Resources: map[uuid.UUID]policies.RenderResource{lab: {Name: "ct-v24-lab", Address: v24Subnet},
			host: {Name: "ct-v24-host", Address: v24Host + "/32"}},
		IdentityMode: policies.IdentityModePortal,
	}
	nodes, err := inst.ListNodes(c, "")
	if err != nil {
		t.Fatal(err)
	}
	owners := map[string]uuid.UUID{userA.Name: memA, userB.Name: memB}
	for _, n := range nodes {
		rn := policies.RenderNode{Tags: n.Tags}
		if n.User != nil && !n.IsTagged() {
			id, ok := owners[n.User.Name]
			if !ok {
				continue // a node of another phase: not part of this tenant's inventory
			}
			rn.Owner = id
		} else if !slices.Contains(n.Tags, v24RouterTag) {
			continue
		}
		in.Nodes = append(in.Nodes, rn)
	}
	pr := func(typ, ref string) policies.Principal { return policies.Principal{Type: typ, Ref: ref} }
	var src policies.PolicySource
	add := func(id string, params policies.TemplateParams) {
		_, frag, err := policies.BuildTemplate(policies.TemplateRequest{TemplateID: id, Params: params})
		if err != nil {
			t.Fatalf("template %s: %v", id, err)
		}
		src.Grants = append(src.Grants, frag.Grants...)
	}
	add(policies.TemplateOwnDevices, policies.TemplateParams{Ports: []string{"tcp:22"}})
	add(policies.TemplateGroupToResource, policies.TemplateParams{GroupID: eng.String(), ResourceID: host.String(), Ports: []string{"tcp:443"}})
	add(policies.TemplateAdminsToDevices, policies.TemplateParams{GroupID: eng.String(), Ports: []string{"tcp:22", "tcp:3389"}})
	add(policies.TemplateSubnetRouter, policies.TemplateParams{GroupID: eng.String(), ResourceID: lab.String(), TagID: router.String(),
		Ports: []string{"tcp:80"}})
	src.Grants = append(src.Grants,
		policies.Grant{Src: []policies.Principal{pr(policies.PrincipalUser, memB.String())},
			Dst: []policies.Principal{pr(policies.PrincipalTag, router.String())}, IP: []string{"tcp:8443"}},
		policies.Grant{Src: []policies.Principal{pr(policies.PrincipalGroup, ops.String())},
			Dst: []policies.Principal{pr(policies.PrincipalTag, web.String())}, IP: []string{"tcp:80"}},
		policies.Grant{Src: []policies.Principal{pr(policies.PrincipalAutogroup, policies.AutogroupMember)},
			Dst: []policies.Principal{pr(policies.PrincipalGroup, eng.String())}, IP: []string{"udp:5353"}})
	run := func(name string, s policies.PolicySource) (int, string) {
		s.SSH = []policies.SSHRule{}
		r := policies.RenderTyped(s, "contract", in)
		if r.Report.Blocking() {
			t.Fatalf("%s: render %+v", name, r.Report.Errors)
		}
		n := 0
		var skipped []string
		for _, tc := range r.Report.Tests {
			if tc.Skipped == "" {
				n++
			} else {
				skipped = append(skipped, fmt.Sprintf("%d:%s", tc.Grant, tc.Skipped))
			}
		}
		if err := inst.CheckPolicy(c, r.Document.Applied); err != nil {
			t.Fatalf("%s: CheckPolicy of the generated tests: %s\n%s", name, describe(err), r.Document.Applied)
		}
		if _, err := inst.SetPolicy(c, r.Document.Applied); err != nil {
			t.Fatalf("%s: SetPolicy: %s", name, describe(err))
		}
		got, err := inst.GetPolicy(c)
		if err != nil || policies.SHA256Hex(got.Data) != r.Document.AppliedSHA256 {
			t.Fatalf("%s: read-back", name)
		}
		// a wrong assertion appended to the generated block is refused: the block is evaluated
		wrong := strings.TrimSuffix(r.Document.Applied, "\n  ]\n}") +
			",\n    {\n      \"src\": \"" + tokA + "\",\n      \"accept\": [\n        \"" + ipB1.String() + ":9\"\n      ]\n    }\n  ]\n}"
		if out := testsOutcome(inst.CheckPolicy(c, wrong)); out != "refused: tests" {
			t.Fatalf("%s: a wrong assertion ⇒ %s", name, out)
		}
		return n, strings.Join(skipped, " ")
	}
	nDeny, skDeny := run("templates without exit node", src)
	withExit := src
	withExit.Grants = slices.Clone(src.Grants)
	_, exitFrag, err := policies.BuildTemplate(policies.TemplateRequest{TemplateID: policies.TemplateExitNode,
		Params: policies.TemplateParams{GroupID: eng.String(), TagID: router.String()}})
	if err != nil {
		t.Fatal(err)
	}
	withExit.Grants = append(withExit.Grants, exitFrag.Grants...)
	nNoDeny, skNoDeny := run("templates with exit node", withExit)
	if nDeny < 4 || nNoDeny != nDeny {
		t.Fatalf("generated tests: %d / %d", nDeny, nNoDeny)
	}
	e.record(t, "P5-T01", "tests sinh tự động (testgen) trên inventory thật: 4 thiết bị, template của danh mục + grant thường",
		fmt.Sprintf("lượt 1 (có deny trên cổng không grant nào nhắc): %d ca, bỏ [%s]; lượt 2 (thêm exit-node ip \"*\" ⇒ không ca deny): %d ca, bỏ [%s]; mỗi lượt CheckPolicy + SetPolicy đạt, GetPolicy khớp sha256; thêm 1 assertion sai vào khối ⇒ CheckPolicy từ chối \"test(s) failed\"",
			nDeny, skDeny, nNoDeny, skNoDeny),
		"render tất định + tests trong chuỗi gửi đi (applied_sha256)")
}
