// Phase 12 (P5-T01): the "tests" block of a policy on the real Headscale of the contract run (the patched build, same
// policy engine as the official v0.29.7), after the policy core of phase 12 (policies_test.go — it runs first: Go runs
// the files of a package in name order) left the instance on the deny-all baseline.
//
//   - V-24 — can "tests" assert access that comes ONLY from "via" or ONLY from autogroup:self? Each question is asked
//     through CheckPolicy (the dry run that runs the block; SetPolicy runs the same evaluator) with a control policy
//     that grants the same access without via/self, and the grant is shown EFFECTIVE on the node that enforces it (the
//     packet filter the router, or the user's own device, receives). Answer recorded as an observation (V-24);
//   - the tests generated by internal/policies (testgen.go) over the real inventory of the run — typed principals,
//     users named mg-<membership>@ as the platform creates them, the templates of the catalog — pass CheckPolicy and
//     SetPolicy, and a wrong assertion appended to the generated block is refused (the block is evaluated, not skipped).
//
// The instance ends with the policy it had before (byte for byte — the register's current application stays true) and
// without the nodes of this test.

