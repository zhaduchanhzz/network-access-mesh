#!/usr/bin/env python3
"""End-to-end test of the key ceremony kit (P2-T04a) with throwaway keys in a simulated root — for a BUILD machine,
never the staging host.

    sudo -n true && python3 -I infrastructure/host/key-ceremony/test_ceremony.py \\
        --worker-image <name@sha256:… | sha256:<local image ID>> --age-dir <dir with age, age-keygen> \\
        [--prefix mgkc-test] [--create-groups] [--keep]

Needs Linux, passwordless sudo, Docker, python3 ≥ 3.11, the worker image (with kek-drill) and the age binaries pinned
in versions.lock (build-age.sh). It drives every step of ceremony.sh: non-TTY steps with pipes, the TTY steps
(show-offline, verify-offline) through a pseudo-terminal (pty) — including the refusals without a TTY.

The keys are generated by ceremony.sh inside the simulated root; this program reads them (sudo) only to compare and
to look for leaks, and NEVER prints them: its output is test names, verdicts, kek_ids and KCVs. Standard library only.
"""
