KIT = pathlib.Path(__file__).resolve().parent
CEREMONY = KIT / "ceremony.sh"
KCV_LABEL = b"meshguard/kek-kcv/v1"
B32 = "qpzry9x8gf2tvdw0s3jn54khce6mua7l"
GROUPS = {"mg-sec-app": 20001, "mg-sec-worker": 20003}

SECRETS: list[str] = []   # every encoding of every throwaway key: leak checks and scrubbing
results = {"pass": 0, "fail": 0}


def kcv(key: bytes) -> str:
    return hmac.new(key, KCV_LABEL, hashlib.sha256).hexdigest()[:8]


def scrub(s: str) -> str:
    for x in sorted(SECRETS, key=len, reverse=True):
        s = s.replace(x, "<SECRET>").replace(x.lower(), "<SECRET>").replace(x.upper(), "<SECRET>")
    return s


def check(ok: bool, name: str, detail: str = "") -> bool:
    print(f"{'PASS' if ok else 'FAIL'} {name}{'' if ok else ' — ' + scrub(detail)[-1500:]}", flush=True)
    results["pass" if ok else "fail"] += 1
    return ok


def leaks(text: str) -> list[str]:
    low = text.lower()
    return [f"{len(x)} chars" for x in SECRETS if x.lower() in low]


def add_secret(value: str, group: int) -> None:
    """Register a secret and the forms it could leak in: whole, per display line (spaced and unspaced)."""
    forms = {value}
    for i in range(0, len(value), group):
        line = value[i:i + group]
        if len(line) >= 16:
            forms.add(line)
            forms.add(" ".join(line[j:j + 4] for j in range(0, len(line), 4)))
    if re.fullmatch(r"[0-9a-f]{64}", value):
        forms.add(base64.b64encode(bytes.fromhex(value)).decode())
    SECRETS.extend(sorted(forms))


class Pty:
    """A child process on a pseudo-terminal (controlling TTY, as with ssh -t) with expect/send."""

    def __init__(self, argv: list[str]):
        self.pid, self.fd = pty.fork()
        if self.pid == 0:  # child
            try:
                os.execvp(argv[0], argv)
            finally:
                os._exit(127)
        self.buf = b""
        self.pos = 0

    def _read(self, timeout: float) -> bool:
        r, _, _ = select.select([self.fd], [], [], timeout)
        if not r:
            return True
        try:
            data = os.read(self.fd, 65536)
        except OSError:
            data = b""
        if not data:
            return False
        self.buf += data
        return True

    def expect(self, pattern: str, timeout: float = 60) -> re.Match:
        rx = re.compile(pattern.encode(), re.S)
        deadline = time.monotonic() + timeout
        while True:
            m = rx.search(self.buf, self.pos)
            if m:
                self.pos = m.end()
                return m
            left = deadline - time.monotonic()
            if left <= 0:
                raise TimeoutError(f"no match for {pattern!r}")
            if not self._read(min(left, 1.0)):
                raise EOFError(f"child ended before {pattern!r}")

    def send(self, s: str) -> None:
        os.write(self.fd, s.encode() + b"\r")

    def wait(self, timeout: float = 120) -> int:
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            pid, status = os.waitpid(self.pid, os.WNOHANG)
            if pid:
                while select.select([self.fd], [], [], 0.2)[0]:  # drain what is left
                    try:
                        data = os.read(self.fd, 65536)
                    except OSError:
                        break
                    if not data:
                        break
                    self.buf += data
                os.close(self.fd)
                return os.waitstatus_to_exitcode(status)
            self._read(0.2)
        os.kill(self.pid, signal.SIGKILL)
        os.waitpid(self.pid, 0)
        os.close(self.fd)
        return -9

    def text(self) -> str:
        return self.buf.decode("utf-8", "replace")


class Env:
    def __init__(self, a: argparse.Namespace):
        self.prefix = a.prefix
        self.base = pathlib.Path(tempfile.mkdtemp(prefix=f"{a.prefix}-"))
        self.root = self.base / "root"
        self.tmp = f"/run/{a.prefix}-ceremony"
        self.age = str(pathlib.Path(a.age_dir).resolve())
        self.image = a.worker_image
        self.mg = self.root / "opt" / "meshguard"
        self.kr = {"kek-app": self.mg / "secrets" / "kek-app", "kek-ops": self.mg / "secrets" / "kek-ops"}
        self.created_groups: list[str] = []

    def cmd(self, *step: str, **override: str) -> list[str]:
        env = {"MGKC_ROOT": str(self.root), "MGKC_TMP": self.tmp, "MGKC_AGE_DIR": self.age,
               "MGKC_WORKER_IMAGE": self.image}
        env.update(override)
        return ["sudo", "-n", "env", *[f"{k}={v}" for k, v in env.items()], "bash", str(CEREMONY), *step]


def sudo(*argv: str, check_: bool = True, **kw) -> subprocess.CompletedProcess:
    return subprocess.run(["sudo", "-n", *argv], check=check_, text=True, capture_output=True, **kw)


def run(e: Env, *step: str, **override: str) -> tuple[int, str]:
    p = subprocess.run(e.cmd(*step, **override), stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
                       stderr=subprocess.STDOUT, text=True, timeout=900)
    return p.returncode, p.stdout


def read_secret(path: pathlib.Path | str) -> str:
    return sudo("cat", str(path)).stdout


def mode(path: pathlib.Path | str) -> str:
    return sudo("stat", "-c", "%U:%G %a", str(path)).stdout.strip()


def mounted(path: str) -> bool:
    return subprocess.run(["mountpoint", "-q", path]).returncode == 0


# ------------------------------------------------------------------------------------------------ fixtures

def setup(e: Env, create_groups: bool) -> None:
    for g, gid in GROUPS.items():
        have = subprocess.run(["getent", "group", g], capture_output=True, text=True).stdout
        if have:
            if have.split(":")[2] != str(gid):
                sys.exit(f"group {g} exists with another GID")
            continue
        if not create_groups:
            sys.exit(f"group {g} ({gid}) missing — rerun with --create-groups")
        sudo("groupadd", "--system", "--gid", str(gid), g)
        e.created_groups.append(g)
    for d, m in [(e.root, "0755"), (e.root / "opt", "0755"), (e.mg, "0755"), (e.mg / "core", "0755"),
                 (e.mg / "secrets", "0700"), (e.root / "etc", "0755"), (e.root / "etc" / "sudoers.d", "0755"),
                 (e.root / "etc" / "pam.d", "0755"), (e.root / "proc", "0755")]:
        sudo("install", "-d", "-o", "root", "-g", "root", "-m", m, str(d))


def teardown(e: Env) -> None:
    if mounted(e.tmp):
        sudo("find", e.tmp, "-type", "f", "-exec", "shred", "-u", "-z", "-n", "1", "--", "{}", "+", check_=False)
        sudo("umount", e.tmp, check_=False)
    sudo("rm", "-rf", e.tmp, e.tmp + ".lock", str(e.base), check_=False)
    sudo("docker", "rm", "-f", f"{e.prefix}-mounttest", check_=False)
    for g in e.created_groups:
        sudo("groupdel", g, check_=False)


def live_secrets(e: Env) -> dict:
    """Read the throwaway keys of the running ceremony (never printed) and register them for leak checks."""
    s: dict = {}
    for name, d in e.kr.items():
        kid = read_secret(d / "ACTIVE").strip()
        hexv = read_secret(d / kid).strip()
        add_secret(hexv, 16)
        s[name] = {"id": kid, "hex": hexv, "kcv": kcv(bytes.fromhex(hexv))}
    ident = [ln for ln in read_secret(f"{e.tmp}/recovery.agekey").splitlines() if ln.startswith("AGE-SECRET-KEY-1")][0]
    add_secret(ident, 1000)
    add_secret(ident[len("AGE-SECRET-KEY-1"):], 20)
    s["identity"] = ident[len("AGE-SECRET-KEY-1"):]
    s["recipient"] = [ln for ln in sudo("cat", str(e.mg / "core" / "keys" / "backup-recovery.age-recipient")).stdout
                      .splitlines() if ln.startswith("age1")][0]
    return s


# ------------------------------------------------------------------------------------------------ TTY drivers

def show_offline(e: Env) -> tuple[int, dict, str]:
    """Drive show-offline and parse what the owner would copy."""
    p = Pty(e.cmd("show-offline"))
    shown: dict = {}
    p.expect(r"\[Enter\]> ")
    p.send("")
    for _ in range(2):
        m = p.expect(r'KEK "(kek-app|kek-ops)" ===(.*?)\[Enter\]> ')
        block = m.group(2).decode()
        lines = re.findall(r"dòng (\d):  ((?:[0-9a-f]{4} ?){4})", block)
        shown[m.group(1).decode()] = {
            "id": re.search(r"kek_id   : (\S+)", block).group(1),
            "hex": "".join(v.replace(" ", "") for _, v in lines),
            "kcv": re.search(r"KCV      : ([0-9a-f]{8})", block).group(1),
            "lines": len(lines)}
        p.send("")
    m = p.expect(r"age X25519\) ===(.*?)\[Enter\]> ")
    block = m.group(1).decode()
    lines = re.findall(r"dòng (\d):  ([0-9A-Z ]+?)\r?\n", block)
    shown["identity"] = "".join(v.replace(" ", "") for _, v in lines)
    shown["identity_lines"] = len(lines)
    p.send("")
    p.expect(r"\[show-offline\] Xong")
    code = p.wait()
    return code, shown, p.text()


def mutate(s: str, pos: int, alphabet: str) -> str:
    c = s[pos]
    alt = next(x for x in alphabet if x != c.lower() and x != c)
    return s[:pos] + (alt.upper() if c.isupper() else alt) + s[pos + 1:]


def spaced(s: str, sep: str = " ") -> str:
    return sep.join(s[i:i + 4] for i in range(0, len(s), 4))


def plan_for(s: dict, style: str = "spaced") -> dict:
    """A verify-offline input plan that matches the secrets, one attempt per prompt."""
    def kek_lines(h: str) -> list[list[str]]:
        out = []
        for i in range(0, 64, 16):
            line = h[i:i + 16]
            out.append([{"spaced": spaced(line), "upper": spaced(line).upper(), "dashes": spaced(line, "-")}[style]])
        return out
    ident = s["identity"]
    return {name: {"id": [s[name]["id"]], "lines": kek_lines(s[name]["hex"]), "kcv": spaced(s[name]["kcv"])}
            for name in ("kek-app", "kek-ops")} | {
        "recovery": {"lines": [[spaced(ident[i:i + 20]).lower() if style == "upper" else spaced(ident[i:i + 20])]
                               for i in range(0, 58, 20)]}}


def verify(e: Env, copy: int, plan: dict, typeahead: bool = False) -> tuple[int, str, str]:
    """Drive verify-offline. typeahead: the first secret line of kek-app is typed together with the kek_id, before
    its prompt appears (an owner typing ahead) — it must not be echoed either."""
    p = Pty(e.cmd("verify-offline", "--copy", str(copy)))
    for name in ("kek-app", "kek-ops"):
        it = plan[name]
        early = typeahead and name == "kek-app"
        for i, a in enumerate(it["id"]):
            p.expect(re.escape(f"[{name}] kek_id> "))
            if early and i == len(it["id"]) - 1:
                os.write(p.fd, a.encode() + b"\r" + it["lines"][0][0].encode() + b"\r")
            else:
                p.send(a)
        for n, attempts in enumerate(it["lines"], 1):
            for j, a in enumerate(attempts):
                p.expect(re.escape(f"[{name}] dòng {n}> "))
                if not (early and n == 1 and j == 0):
                    p.send(a)
        p.expect(re.escape(f"[{name}] KCV ghi trên bản sao> "))
        p.send(it["kcv"])
    for n, attempts in enumerate(plan["recovery"]["lines"], 1):
        for a in attempts:
            p.expect(re.escape(f"[khôi phục] dòng {n}> "))
            p.send(a)
    m = p.expect(r"\[verify-offline\] Bản \d: (PASS|FAIL)")
    code = p.wait()
    return code, m.group(1).decode(), p.text()


