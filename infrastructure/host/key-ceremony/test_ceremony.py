def scenario(e: Env) -> None:
    t0 = time.monotonic()
    check(kcv(bytes(range(32))) == "1dccd334" and kcv(b"\xff" * 32) == "185483a4",
          "KCV test vectors (same as TestKCVTestVectors in Go)")

    code, out = run(e, "preflight")
    check(code == 0 and "KẾT QUẢ: ĐẠT" in out, "preflight on a clean simulated host", out)

    # ---- preflight refusals, one condition at a time
    etc = e.root / "etc"
    refusals = [
        ("sudo I/O logging", etc / "sudoers.d" / "iolog", "Defaults log_output\n", "sudo đang ghi I/O"),
        ("pam_tty_audit", etc / "pam.d" / "common-session", "session required pam_tty_audit.so enable=*\n", "pam_tty_audit đang bật"),
        ("swap on", e.root / "proc" / "swaps",
         "Filename\tType\tSize\tUsed\tPriority\n/swap.img file 1048572 0 -2\n", "swap đang bật"),
    ]
    for name, path, content, want in refusals:
        subprocess.run(["sudo", "-n", "tee", str(path)], input=content, text=True, capture_output=True, check=True)
        code, out = run(e, "preflight")
        check(code == 1 and want in out, f"preflight refuses: {name}", out)
        sudo("rm", "-f", str(path))
    bad_age = e.base / "bad-age"
    bad_age.mkdir()
    for b in ("age", "age-keygen"):
        shutil.copy2(pathlib.Path(e.age) / b, bad_age / b)
    with open(bad_age / "age", "ab") as f:
        f.write(b"\0")
    code, out = run(e, "preflight", MGKC_AGE_DIR=str(bad_age))
    check(code == 1 and "age: sha256" in out, "preflight refuses: age binary differs from versions.lock", out)
    code, out = run(e, "preflight", MGKC_WORKER_IMAGE="mg-worker:latest")
    check(code == 1 and "chưa có image worker theo digest" in out, "preflight refuses: worker image without digest", out)
    golang = "docker.io/library/golang@sha256:f18c3d73a184fb0582828510722e723b63a93f7188d11dd223d9be6f6880e65d"
    if subprocess.run(["sudo", "-n", "docker", "image", "inspect", golang], capture_output=True).returncode == 0:
        code, out = run(e, "preflight", MGKC_WORKER_IMAGE=golang)
        check(code == 1 and "không có lệnh kek-drill" in out, "preflight refuses: image without kek-drill", out)

    # ---- generate fails half-way ⇒ everything it created is rolled back
    blocker = e.mg / "core" / "keys"
    sudo("touch", str(blocker))
    code, out = run(e, "generate")
    left = [str(p) for p in (e.kr["kek-app"], e.kr["kek-ops"], e.mg / "secrets" / "agent")
            if sudo("test", "-e", str(p), check_=False).returncode == 0]
    check(code != 0 and "THẤT BẠI — gỡ" in out and not left and not mounted(e.tmp) and not os.path.exists(e.tmp),
          "generate failing half-way rolls back (keys, agent dir, tmpfs)", f"exit {code}, left {left}\n{out}")
    sudo("rm", "-f", str(blocker))

    # ---- generate
    t = time.monotonic()
    code, gen_out = run(e, "generate")
    check(code == 0 and "Đã tạo" in gen_out, f"generate ({time.monotonic() - t:.1f} s)", gen_out)
    s = live_secrets(e)
    check(not leaks(gen_out), "generate prints no key material", str(leaks(gen_out)))
    for name, grp in (("kek-app", "mg-sec-app"), ("kek-ops", "mg-sec-worker")):
        d = e.kr[name]
        ok = (mode(d) == f"root:{grp} 750" and mode(d / s[name]["id"]) == f"root:{grp} 440"
              and mode(d / "ACTIVE") == f"root:{grp} 440"
              and read_secret(d / s[name]["id"]) == s[name]["hex"] + "\n"
              and re.fullmatch(rf"staging-{name[4:]}-\d{{8}}-\d{{4}}", s[name]["id"]) is not None)
        check(ok, f"{name}: dir 0750 / files 0440 root:{grp}, 64 hex + newline, kek_id staging-{name[4:]}-<UTC>",
              f"{mode(d)} {mode(d / s[name]['id'])}")
        check(f"{d}/{s[name]['id']}" in gen_out and f"KCV {s[name]['kcv']}" in gen_out,
              f"{name}: KCV printed by generate (bash+python) = KCV computed here ({s[name]['kcv']})", gen_out)
    check(s["kek-app"]["kcv"] != s["kek-ops"]["kcv"], "kek-app and kek-ops hold different keys")
    sk = e.mg / "secrets" / "agent" / "manifest_signing_key"
    pem = read_secret(sk)
    check(mode(sk) == "root:root 400" and mode(e.mg / "secrets" / "agent") == "root:root 700"
          and pem.startswith("-----BEGIN PRIVATE KEY-----\nMC4CAQAwBQYDK2VwBCIEI"),
          "manifest signing key: Ed25519 PKCS#8, root:root 0400 in secrets/agent (0700)", mode(sk))
    SECRETS.append(pem.splitlines()[1])
    pub = sudo("cat", str(e.mg / "core" / "keys" / "manifest-signing.pub.pem")).stdout
    spki = "".join(pub.splitlines()[1:-1])
    check(re.fullmatch(r"MCowBQYDK2VwAyEA[A-Za-z0-9+/]{43}=", spki) is not None
          and mode(e.mg / "core" / "keys" / "manifest-signing.pub.pem") == "root:root 644"
          and f"MG_BACKUP_MANIFEST_PUBKEY={spki}" in run(e, "status")[1],
          "manifest public key: Ed25519 SPKI, 0644, reported by status", spki)
    rec_derived = subprocess.run(["sudo", "-n", f"{e.tmp}/bin/age-keygen", "-y", f"{e.tmp}/recovery.agekey"],
                                 capture_output=True, text=True).stdout.strip()
    check(re.fullmatch(rf"age1[{B32}]{{58}}", s["recipient"]) is not None and rec_derived == s["recipient"]
          and mode(e.mg / "core" / "keys" / "backup-recovery.age-recipient") == "root:root 644",
          "recovery recipient saved (0644) and derived from the tmpfs identity", s["recipient"])
    fs = subprocess.run(["findmnt", "-no", "FSTYPE,OPTIONS", e.tmp], capture_output=True, text=True).stdout
    check(fs.startswith("tmpfs") and "size=65536k" in fs and "mode=700" in fs and "nosuid" in fs,
          "identity only on a dedicated tmpfs (64 MiB, 0700, nosuid,nodev)", fs)
    # look for the secret values themselves on disk (patterns on stdin — never on a command line)
    grep = subprocess.run(["sudo", "-n", "grep", "-rlF", "-f", "-", str(e.base)], input=s["identity"] + "\n",
                          capture_output=True, text=True)
    check(grep.returncode == 1, "no copy of the recovery identity on disk (simulated root and work dir)", grep.stdout)
    grep = subprocess.run(["sudo", "-n", "grep", "-rlF", "-f", "-", str(e.base)],
                          input=s["kek-app"]["hex"] + "\n" + s["kek-ops"]["hex"] + "\n", capture_output=True, text=True)
    check(sorted(grep.stdout.split()) == sorted(str(e.kr[n] / s[n]["id"]) for n in ("kek-app", "kek-ops")),
          "each KEK is on disk only in its keyring file", grep.stdout)

    code, out = run(e, "preflight")
    check(code == 1 and "đã tồn tại" in out, "preflight refuses once keys exist", out)
    before = sudo("sh", "-c", f"find {shlex.quote(str(e.mg))} -type f -exec sha256sum {{}} + | sort").stdout
    code, out = run(e, "generate")
    after = sudo("sh", "-c", f"find {shlex.quote(str(e.mg))} -type f -exec sha256sum {{}} + | sort").stdout
    check(code == 1 and before == after, "generate refuses a second time and changes nothing", out)

    # ---- TTY refusals (the coordinator's automation runs SSH without a TTY)
    for step in (["show-offline"], ["verify-offline", "--copy", "1"]):
        code, out = run(e, *step)
        check(code == 3 and "TỪ CHỐI" in out and not leaks(out), f"{step[0]} without a TTY: refused (exit 3), nothing shown", out)
    outfile = e.base / "redirected.txt"
    for name, shell in (("stdout redirected to a file", f"> {shlex.quote(str(outfile))} 2>&1"),
                        ("stdin from /dev/null", "< /dev/null"),
                        ("stdout piped", "| cat")):
        p = Pty(["bash", "-o", "pipefail", "-c", " ".join(shlex.quote(x) for x in e.cmd("show-offline")) + " " + shell])
        code = p.wait()
        text = p.text() + (outfile.read_text(encoding="utf-8", errors="replace") if outfile.exists() else "")
        check(code == 3 and "TỪ CHỐI" in text and not leaks(text), f"show-offline on a TTY but {name}: refused (exit 3)",
              f"exit {code}")
        outfile.unlink(missing_ok=True)

    # ---- show-offline on a TTY
    t = time.monotonic()
    code, shown, text = show_offline(e)
    ok = (code == 0 and all(shown[n]["id"] == s[n]["id"] and shown[n]["hex"] == s[n]["hex"] and
                            shown[n]["kcv"] == s[n]["kcv"] and shown[n]["lines"] == 4 for n in ("kek-app", "kek-ops"))
          and shown["identity"] == s["identity"] and shown["identity_lines"] == 3)
    check(ok, f"show-offline on a TTY: kek_id, 4×4 groups, KCV, identity in 3 lines match ({time.monotonic() - t:.1f} s)",
          f"exit {code}")
    check(text.count("\x1b[3J") >= 5 and text.rstrip().endswith("verify-offline --copy 1, rồi --copy 2 (nhập lại từ giấy, không hiện chữ)."),
          "show-offline clears screen + scrollback between items and at the end")

    # ---- the ceremony lock: a TTY step waiting for input blocks the coordinator's steps
    p = Pty(e.cmd("verify-offline", "--copy", "1"))
    p.expect(re.escape("[kek-app] kek_id> "))
    code, out = run(e, "drill")
    check(code == 1 and "đang chạy" in out, "lock: drill refused while verify-offline is running", out)
    os.write(p.fd, b"\x03")
    code = p.wait()
    check(code != 0, f"verify-offline interrupted with Ctrl-C (exit {code})")

    # ---- verify-offline: both copies right (input normalisation: spaces, upper case, dashes; a retried typo)
    plan1 = plan_for(s, "upper")
    t = time.monotonic()
    code, verdict, text = verify(e, 1, plan1, typeahead=True)
    check(code == 0 and verdict == "PASS" and text.count(": khớp") == 11,
          f"verify-offline copy 1 (upper case, spaces): PASS, 11 lines match ({time.monotonic() - t:.1f} s)", f"exit {code}")
    check(not leaks(text) and f"[kek-app] kek_id> {s['kek-app']['id']}" in text,
          "verify-offline echoes nothing secret, even typed ahead of the prompt (kek_id is printed back)", str(leaks(text)))
    plan2 = plan_for(s, "dashes")
    good = s["kek-app"]["hex"][16:32]
    plan2["kek-app"]["lines"][1] = [spaced(mutate(good, 9, "0123456789abcdef")), spaced(good)]
    ident_l3 = s["identity"][40:58]
    plan2["recovery"]["lines"][2] = [spaced(ident_l3[:-1]), spaced(ident_l3)]   # wrong length: re-asked, not counted
    code, verdict, text = verify(e, 2, plan2)
    check(code == 0 and verdict == "PASS" and "dòng 2: KHÔNG khớp ở nhóm 3 (lần 1/3)" in text
          and "sai định dạng: cần 18 ký tự" in text and not leaks(text),
          "verify-offline copy 2 (dashes; one typo retried; one wrong-length line re-asked): PASS", f"exit {code}")

    # ---- drill
    t = time.monotonic()
    code, out = run(e, "drill")
    dt = time.monotonic() - t
    go_kcv = dict(re.findall(r"kek-drill: (kek-app|kek-ops): kek_id=\S+ kcv live=([0-9a-f]{8}) recovered=\2 ", out))
    check(code == 0 and out.count("kek-drill: PASS (2 keyrings, 2 kek_ids)") == 2 and "KẾT QUẢ: PASS" in out,
          f"drill: kek-drill PASS for copies 1 and 2 ({dt:.1f} s)", out)
    check(go_kcv == {n: s[n]["kcv"] for n in ("kek-app", "kek-ops")},
          f"KCV in Go (kek-drill) = KCV in the scripts = KCV here: {go_kcv}", out)
    procs = re.findall(r"kek-drill: process uid=(\d+) gid=(\d+) groups=([\d,]+) network-interfaces=(\S+)", out)
    check(len(procs) == 2 and all(u == g == "65532" and set(gs.split(",")) == {"20001", "20003", "65532"} and i == "lo"
                                  for u, g, gs, i in procs),
          "kek-drill ran as 65532 with only the keyring groups (20001, 20003) added, network: lo only", out)
    check(out.count("đối chứng âm: khóa sai 1 ký tự ⇒ kek-drill FAIL") == 2
          and out.count("identity khác không giải mã được") == 2 and out.count("giải mã được tin thử") == 2,
          "drill: recovery identity decrypts a test message; both negative controls fail as they must", out)
    check(not leaks(out), "drill output has no key material", str(leaks(out)))
    code, out = run(e, "status")
    check(code == 0 and out.count("verify-offline PASS, drill PASS") == 2 and not leaks(out),
          "status: both copies verified and drilled; public values only", out)

    # ---- failures: a wrong copy is reported and blocks cleanup
    bad = plan_for(s)
    line3 = s["kek-ops"]["hex"][32:48]
    bad["kek-ops"]["lines"][2] = [spaced(mutate(line3, 0, "0123456789abcdef"))] * 3
    code, verdict, text = verify(e, 2, bad)
    check(code == 1 and verdict == "FAIL" and "dòng 3: KHÔNG khớp ở nhóm 1 (lần 3/3)" in text and not leaks(text),
          "verify-offline: a line wrong 3 times ⇒ FAIL", f"exit {code}")
    code, out = run(e, "drill", "--copy", "2")
    check(code == 1 and "KCV differs" in out and "KẾT QUẢ: FAIL" in out and not leaks(out),
          "drill on the wrong copy: kek-drill FAIL (KCV differs)", out)
    code, out = run(e, "cleanup")
    check(code == 1 and "chưa đủ" in out and mounted(e.tmp), "cleanup refused while copy 2 is not PASS", out)

    bad = plan_for(s)
    bad["kek-app"]["kcv"] = mutate(s["kek-app"]["kcv"], 7, "0123456789abcdef")
    code, verdict, text = verify(e, 2, bad)
    check(code == 1 and verdict == "FAIL" and "KCV trên giấy" in text, "verify-offline: wrong KCV on paper ⇒ FAIL", f"exit {code}")

    bad = plan_for(s)
    bad["recovery"]["lines"][1] = [spaced(mutate(s["identity"][20:40], 5, B32.upper()))] * 3
    code, verdict, text = verify(e, 2, bad)
    check(code == 1 and verdict == "FAIL" and "KHÔNG suy ra được recipient" in text and not leaks(text),
          "verify-offline: recovery identity wrong ⇒ FAIL (recipient not derived)", f"exit {code}")
    code, out = run(e, "drill", "--copy", "2")
    check(code == 1 and "khóa khôi phục: KHÔNG giải mã được" in out and not leaks(out),
          "drill on that copy: the recovery identity does not decrypt ⇒ FAIL", out)

    bad = plan_for(s)
    bad["kek-ops"]["id"] = [s["kek-ops"]["id"] + "x"] * 3
    code, verdict, text = verify(e, 2, bad)
    check(code == 1 and verdict == "FAIL" and "kek_id KHÔNG khớp" in text, "verify-offline: wrong kek_id ⇒ FAIL", f"exit {code}")
    code, out = run(e, "drill", "--copy", "2")
    check(code == 1 and "ACTIVE differs" in out and "missing from the recovered keyring" in out,
          "drill on that copy: kek-drill FAIL (ACTIVE differs, kek_id missing)", out)

    code, verdict, text = verify(e, 2, plan_for(s))
    code2, out = run(e, "drill", "--copy", "2")
    check(code == 0 and verdict == "PASS" and code2 == 0, "copy 2 re-entered correctly: verify PASS, drill PASS", out)

    # ---- cleanup
    code, out = run(e, "cleanup")
    check(code == 0 and "Đã shred" in out and not mounted(e.tmp) and not os.path.exists(e.tmp) and not leaks(out),
          "cleanup: tmpfs shredded, unmounted, removed", out)
    p = Pty(e.cmd("show-offline"))
    code = p.wait()
    check(code == 1 and "không có nghi thức đang dở" in p.text() and not leaks(p.text()),
          "show-offline after cleanup: nothing to show (identity gone)", f"exit {code}")
    code, out = run(e, "status")
    check(code == 0 and "không có nghi thức đang dở" in out and s["kek-app"]["kcv"] in out, "status after cleanup", out)

    # ---- undo (keys never used): refused while a container mounts a keyring
    sudo("docker", "create", "--name", f"{e.prefix}-mounttest", "-v", f"{e.kr['kek-app']}:/x:ro", e.image, check_=True)
    code, out = run(e, "undo", "--keys-never-used")
    check(code == 1 and "KHÔNG gỡ" in out and sudo("test", "-d", str(e.kr["kek-app"]), check_=False).returncode == 0,
          "undo refused while a container mounts kek-app", out)
    sudo("docker", "rm", f"{e.prefix}-mounttest")
    code, out = run(e, "undo")
    check(code == 2, "undo without --keys-never-used: usage error", out)
    code, out = run(e, "undo", "--keys-never-used")
    rest = sudo("find", str(e.mg), "-mindepth", "1").stdout.split()
    check(code == 0 and sorted(rest) == sorted([str(e.mg / "core"), str(e.mg / "secrets")]),
          "undo --keys-never-used: back to the initial layout", f"{out}\n{rest}")

    # ---- abandon a ceremony: generate → cleanup refused → cleanup --abort → undo → preflight OK
    code, _ = run(e, "generate")
    code2, out2 = run(e, "cleanup")
    code3, out3 = run(e, "cleanup", "--abort")
    code4, _ = run(e, "undo", "--keys-never-used")
    code5, _ = run(e, "preflight")
    check((code, code2, code3, code4, code5) == (0, 1, 0, 0, 0) and "Đã bỏ dở" in out3,
          "abandon: generate, cleanup refused, cleanup --abort, undo, preflight OK again", f"{code} {code2} {code3} {code4} {code5}")
    print(f"e2e: {results['pass']} PASS, {results['fail']} FAIL in {time.monotonic() - t0:.0f} s", flush=True)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--worker-image", required=True)
    ap.add_argument("--age-dir", required=True)
    ap.add_argument("--prefix", default="mgkc-test", help="name prefix of the work dir, tmpfs mount and test container")
    ap.add_argument("--create-groups", action="store_true", help="create mg-sec-app/mg-sec-worker if missing (removed after)")
    ap.add_argument("--keep", action="store_true", help="keep the simulated root (debugging)")
    a = ap.parse_args()
    if os.geteuid() == 0:
        sys.exit("run as a normal user with passwordless sudo")
    e = Env(a)
    try:
        setup(e, a.create_groups)
        scenario(e)
    except (TimeoutError, EOFError, subprocess.CalledProcessError, IndexError, KeyError, AttributeError) as x:
        check(False, "scenario aborted", f"{type(x).__name__}: {x}")
    finally:
        if not a.keep:
            teardown(e)
    return 1 if results["fail"] else 0


if __name__ == "__main__":
    sys.exit(main())
